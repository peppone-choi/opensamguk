// 城 위에 세울 **그림**을 고를 때 쓰는 등급.
//
// 城 의 `level` 은 게임 값이고 이 함수는 그 값을 고치지 않는다. 다만 등급표가 등급과 1:1 이
// 된 뒤로(IsoMap2D.BUILDING_TIERS) 등급 하나가 그림 하나를 그대로 결정하는데, 등급 4('이')
// 한 칸이 세계마다 다른 것을 가리키고 있어 그 칸만 갈라 준다.
//
//   han.json(v2)      — 4 는 진짜 이민족이다. 산월·남만·저·강·흉노·오환·선비 7 곳.
//   han-world-v3      — 4 는 **낡은 자리**다. 7 곳 전부 漢 縣이다.
//
// v3 는 legacy 780 판의 城 자리를 번호째 물려받아 이름·좌표·소속만 새로 쓴다
// (build_han_world.py build_v3). 그런데 `level` 은 다시 계산하지 않아서, 이민족이 서 있던
// 자리에 들어온 漢 縣이 '이' 등급을 그대로 이어받았다. 실측(2026-09-10):
//
//   완온현(牂牁郡·익주) ← 흉노(南匈奴·병주)
//   곡창현(益州郡·익주) ← 오환(烏桓·유주)
//   목미현(益州郡·익주) ← 선비(鮮卑·유주)
//   함광현(桂陽郡) ← 산월 · 단양현(丹陽郡) ← 남만 · 남안현(犍為郡) ← 저 · 무렴현(牂牁郡) ← 강
//
// 자리만 물려받았을 뿐 지리가 전혀 맞지 않는다(유주의 오환이 익주의 縣이 됐다). 그래서
// 이 7 곳은 지금 화면에서 **이민족 야영으로 선다** — 이름표는 「곡창현」인데 천막이다.
//
// 등급 자체를 고치는 것은 여기서 하지 않는다. v3 는 `max`·`initial`(城 능력치)도 같은
// 자리에서 물려받아 level 과 짝이 맞아 있어서, level 만 옮기면 짝이 깨진다. 그건 세계
// 밸런스 결정이라 생성기에서 따로 다뤄야 한다. 여기서는 **그림만** 이름표와 맞춘다.

import { isHanCounty } from './cityName';

/** 이민족 야영이 서는 등급. */
const TRIBAL_LEVEL = 4;

/**
 * 縣 그림의 기본형 — 장현(11).
 *
 * 이 7 곳의 縣 등급(영현/장현)을 가릴 근거가 없다. 생성기의 `county_level()` 은
 * 「郡戶 ÷ 縣수 ≥ 1만」(續漢書 百官志 「萬戶以上為令，不滿為長」)으로 가르는데 그 값이
 * 런타임에는 없고, 같은 郡의 형제 縣에서 빌려 오는 것도 안 된다 — 익주군·장가군은 형제가
 * 전부 郡 등급이라 빌릴 縣 이 없다(실측). 그래서 사료의 기본값인 長(불만만호) 쪽으로 둔다.
 * 지어낸 등급이 아니라 **근거 없음의 표시**다.
 */
const COUNTY_FALLBACK_LEVEL = 11;

/** cityIconLevel 이 보는 만큼. PlacedCity 가 이 모양을 만족한다. */
export interface CityIconInput {
  id: number;
  name: string;
  level: number;
  nameCh?: string;
}

/** 이 城 위에 세울 그림을 고를 등급. 게임 등급을 바꾸지 않는다. */
export function cityIconLevel(city: CityIconInput): number {
  // 郡縣 안의 縣 위에는 이민족 야영을 세우지 않는다. 그 밖은 손대지 않는다 —
  // v2 의 흉노·선비는 진짜 이민족이라 4 그대로 간다.
  if (city.level === TRIBAL_LEVEL && isHanCounty(city)) return COUNTY_FALLBACK_LEVEL;
  return city.level;
}
