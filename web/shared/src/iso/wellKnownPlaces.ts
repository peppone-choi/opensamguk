// 縣 을 떼고 이름만 적는 지명 — **편집 목록**이다.
//
// 배경: 「지도나 도시 출력은 군현제 안이면 뭐뭐현으로 통일해」(2026-09-10) 로 縣 을 붙여 왔는데,
// 장안·낙양처럼 널리 알려진 이름은 「장안현」보다 「장안」이 알아보기 쉽다(2026-09-22 사용자 판단).
//
// **규칙으로 뽑을 수 없어서 목록이다.** 城 등급(경·특·대…)은 後漢 220 년의 행정 서열이라 유명도를
// 따라가지 않는다 — 손오의 수도가 될 건업현과 양양현·수춘현은 장현(가장 낮은 축)이고, 조조의
// 수도 허현은 영현이다. 그래서 등급으로 「유명한 곳」을 판정하려 하면 틀린다.
//
// 목록의 근거는 코에이 삼국지 시리즈의 도시 집합이다(나무위키 「삼국지 시리즈/도시」, 2026-08-18
// 판이 郡·縣 까지 밝혀 둔 것을 썼다). 그 기사가 괄호로 (郡 縣) 을 밝힌 것 가운데 **우리 1133 판
// 데이터에 같은 짝으로 실제 있는 것만** 넣었다. 대조는 `tools/web/check_well_known_places.py`.
//
// 키는 **(郡, 縣) 짝**이다. 縣 이름만으로는 동명이지가 갈리지 않는다 — 장안현은 경조윤과 회계군에
// 둘 있고 유명한 쪽은 경조윤이다.
//
// 들어가지 않은 것과 그 이유:
//   - 진양(태원군)·복양(동군) — 우리 판에는 그 이름이 **다른 郡** 에만 있다(무릉군 진양현,
//     남양군 복양현). 유명한 쪽이 아니므로 떼면 엉뚱한 곳의 이름이 바뀐다.
//   - 영안(파동군) — 촉한이 魚復縣 을 개칭한 이름이라 後漢 220 년 단면에 없다.
//   - 건안(회계군) — 우리 판에는 예장군 건안현만 있다.
//   - 계(광양군)·하변(무도군)·자동(자동군)·말릉(단양군) — 우리 판에 그 짝이 없다.
//     말릉은 개칭 뒤 이름인 **건업현**으로 실려 있어 그쪽을 넣었다.
//   - 여남·장사·강하·계양·무릉·한중·회계·북해·북평·상용·영창·운남·서량 등 — 기사에서도 **郡**
//     이름을 도시명으로 쓴 것이다. 縣 이름이 아니므로 「縣 을 뗀다」로는 그 이름이 나오지 않는다
//     (예: 장사군의 治所 는 임상현이다). 郡 이름으로 바꿔 적을지는 따로 정할 일이다.

// **아직 배선하지 않았다.** `cityDisplayName` 에 바로 걸었더니 서버가 구워 둔 `meta.displayName`
// 과 갈라져 전수 대조 테스트가 깨졌다(`cityName.test.ts` — 「로그와 지도가 한 글자도 다르지 않게
// 하는 유일한 방법」이 그 값이다). 縣 을 떼려면 생성기(`build_han_world.py`)가 displayName 을
// 그렇게 굽고 han-world-v3 핀 사슬을 다시 구워야 한다. 그때까지 이 목록은 자료로만 둔다.

/** `郡\t縣` 로 맞추는 집합. 郡 을 모르면(서버가 안 실어 보내면) 이 목록을 쓰지 않는다. */
const WELL_KNOWN = new Set([
    // 사예 · 옹주
    '하남윤\t낙양현', // 낙양 — 후한·조위·서진의 수도
    '경조윤\t장안현', // 장안 — 전한의 수도
    '홍농군\t홍농현', // 홍농
    // 예주 · 연주 · 서주
    '영천군\t허현', // 허(허창) — 후한의 마지막 수도
    '진류군\t진류현', // 진류
    '패국\t패현', // 소패
    '패국\t초현', // 초 — 조조의 고향
    '하비국\t하비현', // 하비
    '광릉군\t광릉현', // 광릉
    // 기주 · 청주 · 유주
    '위군\t업현', // 업
    '발해군\t남피현', // 남피
    '평원군\t평원현', // 평원
    '감릉군\t감릉현', // 감릉
    '대군\t대현', // 대
    '요동군\t양평현', // 양평(요동)
    // 형주
    '남군\t양양현', // 양양
    '남군\t강릉현', // 강릉
    '남양군\t완현', // 완
    '남양군\t신야현', // 신야
    // 양주(강동)
    '단양군\t건업현', // 건업 — 손오의 수도
    '구강군\t수춘현', // 수춘
    '예장군\t시상현', // 시상
    '오군\t오현', // 오
    // 익주
    '촉군\t성도현', // 성도 — 촉한의 수도
    '파군\t강주현', // 강주
    '영창군\t불위현', // 불위(영창)
]);

/**
 * 이 城 을 이름만으로 적을지.
 *
 * @param jun 소속 郡 표기명. 없으면 판정하지 않는다(false) — 동명이지를 잘못 떼는 것보다 낫다.
 * @param county `뭐뭐현` 까지 붙은 縣 이름.
 */
export function isWellKnownPlace(jun: string | undefined, county: string): boolean {
    if (!jun) return false;
    return WELL_KNOWN.has(`${jun}\t${county}`);
}

/** 목록에 든 (郡, 縣) 짝 — 데이터 대조 도구가 읽는다. */
export const WELL_KNOWN_PLACE_PAIRS: readonly (readonly [string, string])[] =
    [...WELL_KNOWN].map((key) => {
        const [jun, county] = key.split('\t');
        return [jun, county] as const;
    });
