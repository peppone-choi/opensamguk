    # 「垂」가 사전(lex) 안 딴 지역 실존 지명(垂水 등)과 우연히 겹쳐 가짜 縣
    # 「垂」(註 「山，本敦物」)를 냈고, 원래 槐里 절 註 파편(周曰/犬丘/，高/帝改)
